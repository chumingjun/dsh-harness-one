#!/bin/sh
# Build dsh-ccpg-scheme native results client bundle.
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
PLUGIN_DIR="$HERE/dsh-ccpg-scheme"
SRC="$PLUGIN_DIR/src/client.jsx"
OUT="$PLUGIN_DIR/lib/client.js"
BROWSER_SRC="$PLUGIN_DIR/src/browser.jsx"
BROWSER_OUT="$PLUGIN_DIR/lib/browser.js"
NODE_BIN="${DSH_NODE:-${WF1_NODE:-node}}"
CHECK_ONLY=0
[ "${1:-}" = "--check" ] && CHECK_ONLY=1

[ -f "$SRC" ] || { echo "✗ 缺源文件: $SRC"; exit 1; }

"$NODE_BIN" - "$PLUGIN_DIR" "$SRC" "$OUT" "$CHECK_ONLY" <<'NODE'
const { createRequire } = require('node:module');
const fs = require('node:fs');
const path = require('node:path');

const [pluginDir, src, out, checkOnlyRaw] = process.argv.slice(2);
const checkOnly = checkOnlyRaw === '1';
const candidates = [
  path.resolve(pluginDir, '../../web/node_modules'),
  path.resolve(pluginDir, '../dsh-ccpg-document-preview/node_modules'),
].filter((dir) => fs.existsSync(path.join(dir, 'esbuild')));
if (!candidates.length) throw new Error('missing installed frontend dependencies; run web/document-preview install first');
const deps = candidates[0];
console.log(`scheme deps: ${deps}`);

const requireFromDeps = createRequire(path.join(deps, 'package.json'));
const esbuild = requireFromDeps('esbuild');

const cssPlugin = {
  name: 'inline-css',
  setup(build) {
    build.onLoad({ filter: /\.css$/ }, (args) => {
      const css = fs.readFileSync(args.path, 'utf8');
      return {
        loader: 'js',
        contents: `
          var css = ${JSON.stringify(css)};
          if (typeof document !== "undefined" && !document.getElementById("ccpg-scheme-style")) {
            var style = document.createElement("style");
            style.id = "ccpg-scheme-style";
            style.textContent = css;
            document.head.appendChild(style);
          }
        `,
      };
    });
  },
};

const build = (entry, external = [], format = 'cjs') => esbuild.build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  platform: 'browser',
  format,
  jsx: 'automatic',
  absWorkingDir: pluginDir,
  nodePaths: [deps],
  external,
  plugins: [cssPlugin],
  logLevel: 'silent',
});

Promise.all([
  build(src, ['react']),
  build(path.join(pluginDir, 'src/browser.jsx'), [], 'iife'),
]).then(([result, browserResult]) => {
  const body = result.outputFiles[0].text;
  const text = `// Generated by dsh-plugins/build-scheme.sh. Do not edit.
window.__ModuleLoader__.load({
  id: "dsh-ccpg-scheme",
  factory: function (require) {
    var module = { exports: {} };
    var exports = module.exports;
${body}
    return module.exports;
  }
});
`;
  const browserText = `// Generated by dsh-plugins/build-scheme.sh. Do not edit.\n${browserResult.outputFiles[0].text}`;
  new Function(text);
  new Function(browserText);
  if (!text.includes('window.__ModuleLoader__.load')) throw new Error('bundle missing module loader registration');
  if (checkOnly) {
    if (!fs.existsSync(out)) throw new Error(`bundle missing: ${out}`);
    const current = fs.readFileSync(out, 'utf8');
    if (current !== text) throw new Error('scheme bundle is stale; run sh dsh-plugins/build-scheme.sh');
    const browserOut = path.join(pluginDir, 'lib/browser.js');
    if (!fs.existsSync(browserOut) || fs.readFileSync(browserOut, 'utf8') !== browserText) throw new Error('scheme browser bundle is stale; run sh dsh-plugins/build-scheme.sh');
    console.log(`✓ scheme bundles 与源一致（client ${current.split('\n').length} 行）`);
    return;
  }
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, text);
  const browserOut = path.join(pluginDir, 'lib/browser.js');
  fs.writeFileSync(browserOut, browserText);
  console.log(`✓ ${path.relative(pluginDir, out)} 与 ${path.relative(pluginDir, browserOut)} 已生成`);
}).catch((error) => {
  console.error(error && error.stack || error);
  process.exit(1);
});
NODE
