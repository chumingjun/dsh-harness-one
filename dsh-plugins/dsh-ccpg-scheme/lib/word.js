import MarkdownIt from 'markdown-it';
import JSZip from 'jszip';
import { imageSize } from 'image-size';
import { PNG } from 'pngjs';
import { readFile } from 'node:fs/promises';
import {
  AlignmentType, Document, ExternalHyperlink, HeadingLevel, ImageRun,
  LevelFormat, Packer, Paragraph, Table, TableCell, TableRow, TextRun, WidthType,
} from 'docx';

const markdown = new MarkdownIt({ html: true });
const stableDate = new Date('2000-01-01T00:00:00Z');
const decodePath = (path) => { try { return decodeURIComponent(path); } catch { return path; } };
let svgReady; let webpReady;

async function wordImage(bytes, mime) {
  const originalSize = imageSize(bytes);
  if (![originalSize.width, originalSize.height].every((value) => Number.isSafeInteger(value) && value > 0) || originalSize.width * originalSize.height > 32 * 1024 * 1024) throw new Error('Word image dimensions exceed the pixel limit');
  if (mime === 'image/svg+xml') {
    const { Resvg, initWasm } = await import('@resvg/resvg-wasm');
    svgReady ||= initWasm(await readFile(new URL(import.meta.resolve('@resvg/resvg-wasm/index_bg.wasm'))));
    await svgReady;
    const renderer = new Resvg(bytes, { font: { loadSystemFonts: false } });
    let rendered;
    try {
      if (renderer.imagesToResolve().length) throw new Error('Word SVG requires all images to be embedded');
      rendered = renderer.render();
      bytes = Buffer.from(rendered.asPng()); mime = 'image/png';
    } finally { rendered?.free(); renderer.free(); }
  } else if (mime === 'image/webp') {
    const { default: decode, init } = await import('@jsquash/webp/decode.js');
    webpReady ||= (async () => {
      const binary = await readFile(new URL('./codec/dec/webp_dec.wasm', import.meta.resolve('@jsquash/webp/decode.js')));
      await init(await WebAssembly.compile(binary));
    })();
    await webpReady;
    const image = await decode(bytes);
    if (image.width * image.height > 32 * 1024 * 1024) throw new Error('Word image pixel limit exceeded');
    bytes = PNG.sync.write({ width: image.width, height: image.height, data: Buffer.from(image.data) });
    mime = 'image/png';
  }
  const type = ({ 'image/png': 'png', 'image/jpeg': 'jpg', 'image/gif': 'gif', 'image/bmp': 'bmp' })[mime];
  if (!type) throw new Error(`Word image format unsupported: ${mime}`);
  const size = imageSize(bytes);
  if (![size.width, size.height].every((value) => Number.isSafeInteger(value) && value > 0) || size.width * size.height > 32 * 1024 * 1024) throw new Error('Word image dimensions exceed the pixel limit');
  return { ...size, data: bytes, type };
}

// ZIP dates, document dates, drawing ids and hyperlink ids are generated by docx.
// Normalize only those metadata fields so an unchanged delivery keeps its digest.
async function stableDocument(bytes) {
  const source = await JSZip.loadAsync(bytes); const target = new JSZip(); const ids = new Map();
  for (const file of Object.values(source.files).filter((item) => !item.dir && item.name.endsWith('.rels'))) {
    const xml = await file.async('string');
    for (const match of xml.matchAll(/\bId="([^"]+)"/g)) if (!/^rId\d+$/.test(match[1]) && !ids.has(match[1])) ids.set(match[1], `rIdStable${ids.size + 1}`);
  }
  for (const file of Object.values(source.files).filter((item) => !item.dir).sort((a, b) => a.name.localeCompare(b.name))) {
    let content = await file.async('nodebuffer');
    if (/\.(xml|rels)$/.test(file.name)) {
      let xml = content.toString('utf8');
      for (const [from, to] of ids) xml = xml.replaceAll(`="${from}"`, `="${to}"`);
      let drawing = 0;
      xml = xml.replace(/(<wp:docPr\b[^>]*\bid=")\d+(")/g, (_, before, after) => `${before}${++drawing}${after}`);
      if (file.name === 'docProps/core.xml') xml = xml.replace(/(<dcterms:(?:created|modified)\b[^>]*>)[^<]+/g, '$12000-01-01T00:00:00Z');
      content = Buffer.from(xml);
    }
    target.file(file.name, content, { date: stableDate, createFolders: false });
  }
  return target.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE', compressionOptions: { level: 6 } });
}

export async function createWordDocument(delivery) {
  const assets = new Map((delivery.assets || []).map((asset) => [decodePath(asset.path), asset]));
  const numbering = []; let listCount = 0;

  const imageRun = async (token) => {
    const source = decodePath(token.attrGet('src') || '');
    if (/^[a-z][a-z\d+.-]*:/i.test(source) || source.startsWith('//')) throw new Error('Word requires a local saved image');
    const asset = assets.get(source);
    if (!asset?.base64) throw new Error(`Word image unavailable: ${source}`);
    const image = await wordImage(Buffer.from(asset.base64, 'base64'), asset.mime);
    const { data, type } = image;
    const scale = Math.min(1, 600 / image.width, 820 / image.height);
    return new ImageRun({ data, type, transformation: { width: Math.max(1, Math.round(image.width * scale)), height: Math.max(1, Math.round(image.height * scale)) }, altText: { name: token.content, title: token.content, description: token.content } });
  };

  const inline = async (tokens, initial = {}) => {
    const result = []; let style = { ...initial }; const links = [];
    const push = (run) => (links.length ? links.at(-1).children : result).push(run);
    for (const token of tokens || []) {
      switch (token.type) {
        case 'text': push(new TextRun({ ...style, text: token.content })); break;
        case 'code_inline': push(new TextRun({ ...style, text: token.content, font: 'Consolas' })); break;
        case 'softbreak': case 'hardbreak': push(new TextRun({ break: 1 })); break;
        case 'strong_open': style.bold = true; break;
        case 'strong_close': style.bold = initial.bold; break;
        case 'em_open': style.italics = true; break;
        case 'em_close': style.italics = initial.italics; break;
        case 's_open': style.strike = true; break;
        case 's_close': style.strike = false; break;
        case 'image': push(await imageRun(token)); break;
        case 'link_open': links.push({ link: token.attrGet('href'), children: [] }); break;
        case 'link_close': {
          const link = links.pop();
          push(new ExternalHyperlink(link)); break;
        }
        case 'html_inline': throw new Error('Word HTML is unsupported; use structured Markdown before export');
        default: throw new Error(`Word inline content unsupported: ${token.type}`);
      }
    }
    return result;
  };

  const tokens = markdown.parse(delivery.markdown || '', {}); const children = []; const lists = []; const items = []; let quoteDepth = 0;
  const paragraphOptions = () => {
    const list = lists.at(-1); const item = items.at(-1);
    const options = { spacing: { after: 120 }, ...(quoteDepth ? { indent: { left: quoteDepth * 360 } } : {}) };
    if (list && item && !item.emitted) {
      options.numbering = { reference: list.reference, level: Math.min(lists.length - 1, 8) }; item.emitted = true;
    }
    return options;
  };
  for (let index = 0; index < tokens.length; index++) {
    const token = tokens[index];
    if (token.type === 'paragraph_open' || token.type === 'heading_open') {
      const content = tokens[++index];
      children.push(new Paragraph({ ...paragraphOptions(), ...(token.type === 'heading_open' ? { heading: HeadingLevel[`HEADING_${token.tag.slice(1)}`] } : {}), children: await inline(content.children) }));
      index++;
    } else if (token.type === 'bullet_list_open' || token.type === 'ordered_list_open') {
      const reference = `list-${++listCount}`; const ordered = token.type === 'ordered_list_open';
      numbering.push({ reference, levels: Array.from({ length: 9 }, (_, level) => ({ level, format: ordered ? LevelFormat.DECIMAL : LevelFormat.BULLET, text: ordered ? `%${level + 1}.` : '•', start: ordered ? Number(token.attrGet('start') || 1) : 1, alignment: AlignmentType.LEFT, style: { paragraph: { indent: { left: (level + 1) * 360, hanging: 180 } } } })) });
      lists.push({ reference });
    } else if (token.type === 'bullet_list_close' || token.type === 'ordered_list_close') lists.pop();
    else if (token.type === 'list_item_open') items.push({ emitted: false });
    else if (token.type === 'list_item_close') items.pop();
    else if (token.type === 'blockquote_open') quoteDepth++;
    else if (token.type === 'blockquote_close') quoteDepth--;
    else if (token.type === 'fence' || token.type === 'code_block') {
      children.push(new Paragraph({ ...paragraphOptions(), children: token.content.replace(/\n$/, '').split('\n').map((line, position) => new TextRun({ text: line, font: 'Consolas', ...(position ? { break: 1 } : {}) })) }));
    } else if (token.type === 'hr') children.push(new Paragraph({ thematicBreak: true }));
    else if (token.type === 'table_open') {
      const rows = []; let cells; let cell;
      while (tokens[++index]?.type !== 'table_close') {
        const part = tokens[index];
        if (!part) throw new Error('Word table is incomplete');
        if (part.type === 'tr_open') cells = [];
        else if (part.type === 'tr_close') rows.push(new TableRow({ children: cells }));
        else if (part.type === 'th_open' || part.type === 'td_open') cell = { header: part.type === 'th_open', style: part.attrGet('style'), children: [] };
        else if (part.type === 'inline') cell.children = await inline(part.children, { bold: cell.header });
        else if (part.type === 'th_close' || part.type === 'td_close') cells.push(new TableCell({ children: [new Paragraph({ children: cell.children, ...(cell.style?.includes('right') ? { alignment: AlignmentType.RIGHT } : cell.style?.includes('center') ? { alignment: AlignmentType.CENTER } : {}) })] }));
      }
      children.push(new Table({ rows, width: { size: 100, type: WidthType.PERCENTAGE } }));
    } else if (token.type === 'html_block') throw new Error('Word HTML is unsupported; use structured Markdown before export');
    else throw new Error(`Word block content unsupported: ${token.type}`);
  }
  const document = new Document({ title: delivery.projectId || '完整方案', creator: 'CCPG Scheme', styles: { default: { document: { run: { font: 'Microsoft YaHei', size: 22 } } } }, numbering: { config: numbering }, sections: [{ children }] });
  return stableDocument(await Packer.toBuffer(document));
}
